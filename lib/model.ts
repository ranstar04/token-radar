// Token Radar's model (radar-2): one snapshot of the protocol universe in, one ranked board out.
//
// The board covers every slug in the snapshot's watchlist (the floor, never a ceiling) and adds every
// rankable pre-token protocol below the watchlist floor: the early rows the radar exists to find. A
// protocol is pre-token when its record carries no token (no market cap, no CoinGecko id, no symbol);
// the snapshot's live-token protocols are kept apart and shown as the market's own values, never mixed
// into the ranked board.
//
// Implied value is a comparables model, computed from the snapshot's own figures only. No protocol
// name is ever special-cased: the same function scores every row.
//
//   multiple     = the category's median market-cap-to-TVL ratio among the snapshot's live-token
//                  protocols (at least 3 comparables), else the whole snapshot's median; clamped
//                  to [0.05, 1.50]. A lending protocol is priced like lending protocols trade, a
//                  bridge like bridges trade.
//   base         = tvl_usd x multiple
//   growth       = clamp(change_7d, -50, +100) per cent
//   growthMult   = 1 + 0.35 x growth / 100
//   maturity     = 0.70 + 0.50 x min(age_days, 1460) / 1460   (age unknown: 0.90)
//   breadth      = 1 + 0.03 x min(max(chains - 1, 0), 10)
//   implied      = max(1, round(base x growthMult x maturity x breadth))
//
// The constants are stated in the dashboard's method section, and the page recomputes every row from
// the same figures, so the board, the screenshots and the code visibly agree.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

